-- DevSync: registro persistente de postulaciones recibidas por el formulario.
-- Ejecutar una vez en Supabase > SQL Editor.

create table if not exists public.postulaciones (
  id bigint generated by default as identity primary key,
  application_id text not null unique,
  applicant_id text not null,
  nombre text not null,
  correo text not null,
  vacante_titulo text not null,
  vacante_referencia text not null,
  etapa text not null default 'Postulantes',
  fecha_postulacion date not null default current_date,
  origen text not null default 'Formulario DevSync',
  sync_status text not null default 'Recibido',
  cv_path text,
  cv_url text,
  linkedin_url text,
  telefono text,
  pais text,
  ciudad text,
  first_name text,
  surname text,
  document_type text,
  document_number text,
  consentimiento_tratamiento_datos boolean not null default false,
  consentimiento_fecha timestamptz,
  evaluacion_preseleccion jsonb,
  created_at timestamptz not null default now(),
  constraint postulaciones_correo_vacante_unique unique (correo, vacante_referencia)
);

create index if not exists postulaciones_fecha_idx on public.postulaciones (created_at desc);
create index if not exists postulaciones_vacante_idx on public.postulaciones (vacante_referencia);

alter table public.postulaciones enable row level security;
grant select, insert, update, delete on public.postulaciones to service_role;
grant usage, select on sequence public.postulaciones_id_seq to service_role;
-- No se crean políticas anon/authenticated: el backend accede con la clave
-- secreta de servidor. Nunca poner esa clave en componentes del navegador.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('hojas-de-vida', 'hojas-de-vida', false, 5242880, array['application/pdf'])
on conflict (id) do update set
  public = false,
  file_size_limit = 5242880,
  allowed_mime_types = array['application/pdf'];

